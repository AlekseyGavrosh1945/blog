// генерируем svg-заглушку с названием статьи, чтобы картинки работали без интернета
function createImage(string $title, string $path, int $seed): void
{
    $palettes = [
        ['#4c6ef5', '#364fc7'],
        ['#e8590c', '#d9480f'],
        ['#2f9e44', '#2b8a3e'],
        ['#ae3ec9', '#862e9c'],
        ['#e03131', '#c92a2a'],
        ['#1971c2', '#1864ab'],
        ['#f08c00', '#e67700'],
        ['#495057', '#212529'],
    ];
    [$top, $bottom] = $palettes[$seed % count($palettes)];

    $y = 225 - (count(wrap($title, 24)) - 1) * 26;
    $text = '';
    foreach (wrap($title, 24) as $line) {
        $text .= sprintf(
            '<text x="400" y="%d" text-anchor="middle" dominant-baseline="middle" font-family="Arial, sans-serif" font-size="36" font-weight="bold" fill="#fff">%s</text>',
            $y,
            htmlspecialchars($line, ENT_XML1)
        );
        $y += 46;
    }

    $svg = '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="450" viewBox="0 0 800 450">'
        . '<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
        . '<stop offset="0%" stop-color="' . $top . '"/>'
        . '<stop offset="100%" stop-color="' . $bottom . '"/>'
        . '</linearGradient></defs>'
        . '<rect width="800" height="450" fill="url(#g)"/>'
        . $text
        . '</svg>';

    file_put_contents($path, $svg);
}

function wrap(string $text, int $width): array
{
    $lines = [];
    $current = '';
    foreach (explode(' ', $text) as $word) {
        $next = $current === '' ? $word : $current . ' ' . $word;
        if ($current !== '' && mb_strlen($next) > $width) {
            $lines[] = $current;
            $current = $word;
        } else {
            $current = $next;
        }
    }
    if ($current !== '') {
        $lines[] = $current;
    }

    return array_slice($lines, 0, 3);
}
